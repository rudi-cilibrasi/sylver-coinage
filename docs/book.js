// An independent in-browser checker for The Book's certificates.
//
// It re-implements the arena referee's closed proof rules (finite leaf,
// winning edge, complete cover with the finite or Quiet End tail) without
// sharing code with sylver/arena/proof.py, and replays finite leaves with
// solver.js, the JavaScript port of the exact evaluator. Positions are
// canonical comma-separated minimal generators, as in the certificates.
"use strict";

const NODE_SOLVER = typeof module !== "undefined" ? require("./solver.js") : null;
function frob(gens) { return NODE_SOLVER ? NODE_SOLVER.frobeniusNumber(gens) : frobeniusNumber(gens); }

function gcdOf(values) {
  let g = 0;
  for (const v of values) { let a = g, b = v; while (b) { [a, b] = [b, a % b]; } g = a; }
  return g;
}

// Membership in the semigroup generated by `gens`, for 0..limit.
function members(gens, limit) {
  const inS = new Uint8Array(limit + 1);
  inS[0] = 1;
  for (let n = 1; n <= limit; ++n) {
    for (const g of gens) { if (g <= n && inS[n - g]) { inS[n] = 1; break; } }
  }
  return inS;
}

function minimalGenerators(values) {
  const sorted = [...new Set(values)].sort((x, y) => x - y);
  const result = [];
  for (const v of sorted) {
    if (!members(result, v)[v]) result.push(v);
  }
  return result;
}

function keyOf(values) { return minimalGenerators(values).join(","); }
function parseKey(key) { return key.split(",").map(Number); }

// The obligations the referee requires a cover to list, in increasing order,
// with its tail rule: every non-losing move of a finite position, or, for a
// short gcd-two position, the even gaps and the odd gaps of its half.
function coverProfile(gens) {
  const d = gcdOf(gens);
  if (d === 1) {
    const f = frob(gens);
    const inS = members(gens, f);
    const moves = [];
    for (let n = 2; n <= f; ++n) if (!inS[n]) moves.push(n);
    return { tail: "finite", moves };
  }
  if (d !== 2 || gens.length === 1) return null;
  const half = gens.map((g) => g / 2);
  const hf = frob(half);
  const inHalf = members(half, hf);
  const gaps = [];
  for (let n = 1; n <= hf; ++n) if (!inHalf[n]) gaps.push(n);
  // Quiet ender: exactly one of x and top-x is a gap, for every 0 <= x <= top.
  const top = gaps[gaps.length - 1];
  const gapSet = new Set(gaps);
  for (let x = 0; x <= top; ++x) {
    if (gapSet.has(x) === gapSet.has(top - x)) return null;   // long position
  }
  const even = gaps.map((g) => 2 * g);
  const odd = gaps.filter((g) => g > 1 && g % 2 === 1);
  return { tail: "quiet-end-v1", moves: [...even, ...odd].sort((x, y) => x - y) };
}

// Check a certificate; `solve(gens)` returns "P" or "N" for a finite
// position. Returns { valid, outcome, leaves, error }.
function checkCertificate(proof, solve) {
  const nodes = proof.nodes;
  const leaves = [];
  const done = new Map();
  const active = new Set();
  function visit(key) {
    if (done.has(key)) return done.get(key);
    if (active.has(key)) throw new Error("circular proof at {" + key + "}");
    const node = nodes[key];
    if (!node) throw new Error("missing node {" + key + "}");
    if (keyOf(parseKey(key)) !== key) throw new Error("noncanonical position {" + key + "}");
    active.add(key);
    const gens = parseKey(key);
    if (node.rule === "finite") {
      if (gcdOf(gens) !== 1) throw new Error("finite leaf with gcd above one: {" + key + "}");
      const outcome = solve(gens);
      leaves.push(key);
      if (outcome !== node.outcome) throw new Error("leaf {" + key + "} is " + outcome + ", not " + node.outcome);
    } else if (node.rule === "edge") {
      if (node.outcome !== "N") throw new Error("an edge proves N");
      const m = node.move;
      if (!Number.isInteger(m) || m < 2 || members(gens, m)[m]) throw new Error("illegal move " + m + " from {" + key + "}");
      if (keyOf([...gens, m]) !== node.child) throw new Error("wrong child for move " + m + " from {" + key + "}");
      if (visit(node.child) !== "P") throw new Error("edge from {" + key + "} does not reach a P child");
    } else if (node.rule === "cover") {
      if (node.outcome !== "P") throw new Error("a cover proves P");
      const profile = coverProfile(gens);
      if (!profile || profile.tail !== node.tail) throw new Error("unsupported tail for {" + key + "}");
      const moves = node.children.map((row) => row.move).sort((x, y) => x - y);
      if (moves.join(",") !== profile.moves.join(",")) throw new Error("incomplete cover of {" + key + "}");
      for (const row of node.children) {
        if (keyOf([...gens, row.move]) !== row.child) throw new Error("wrong child for move " + row.move);
        if (visit(row.child) !== "N") throw new Error("cover child {" + row.child + "} is not N");
      }
    } else {
      throw new Error("unsupported rule " + node.rule);   // baseline facts cannot be checked here
    }
    active.delete(key);
    done.set(key, node.outcome);
    return node.outcome;
  }
  try {
    const outcome = visit(proof.root);
    return { valid: true, outcome, leaves, error: null };
  } catch (e) {
    return { valid: false, outcome: null, leaves, error: e.message };
  }
}

// Largest Frobenius number among a certificate's finite leaves.
function largestLeaf(proof) {
  let largest = 0;
  for (const [key, node] of Object.entries(proof.nodes)) {
    if (node.rule === "finite") largest = Math.max(largest, frob(parseKey(key)));
  }
  return largest;
}

if (typeof module !== "undefined") {
  module.exports = { checkCertificate, coverProfile, keyOf, largestLeaf, minimalGenerators };
}
